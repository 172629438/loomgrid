"""各省分时电价 → 充放电策略推导。

业务口径（用户 2026-11-04 明确）
--------------------------------
· **峰时段全部用来放电，谷时段全部用来充电**
· 尖峰按峰处理（同样全部放电）
· 如果某季节只有平段而没有谷段，评估峰平价差：
  价差够大 → 平段也可以充电；价差不够 → 该季节不充电
· 有谷段时，平段一律不参与（既不充也不放）

数据口径
--------
内置的是**电网代理购电用户的目录分时电价**（政府核定），
不适用于「直接参与市场交易的用户」——2025-12-17 发改委/能源局
1656 号文规定，自 2026-03-01 起市场化用户不再执行政府核定的固定分时电价，
9 地已落地（贵州、河北南网、湖北、陕西、吉林、云南、重庆、辽宁、河南）。
储能售前测算通常按代理购电口径作为基准，所以这里仍以它为准。

每条数据都标了 source（文件出处）和 checked（核验日期）。
政策会变，用之前先核对当地电网最新公告。
"""
