# 平段充电的峰平价差阈值（倍数差）。只有「无谷段」时才用到。
FLAT_SPREAD_THRESHOLD = 0.35


def _merge_intervals(intervals):
    """合并重叠或相邻的时段，返回不重叠区间列表。

    为什么需要：各省政策里尖峰往往是从峰段里「抠」出来的（如北京夏季
    16-17 时尖峰原本属于平段），录入时若同时列在 peak 和 flat 里，
    简单的拼接会让同一时刻被数两次。合并后只留一份。

    跨午夜区间（start > end）先拆成两段再合。
    """
    flat_iv = []
    for a, b in intervals:
        a, b = float(a), float(b)
        if b > a:
            flat_iv.append((a, b))
        elif b < a:                 # 跨午夜
            flat_iv.append((a, 24.0))
            flat_iv.append((0.0, b))
    if not flat_iv:
        return []
    flat_iv.sort()
    out = [list(flat_iv[0])]
    for a, b in flat_iv[1:]:
        if a <= out[-1][1] + 1e-9:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    # 首尾相接（0 与 24）的合并：把 (22,24)+(0,6) 合回跨午夜形式 (22,6)
    if len(out) > 1 and out[0][0] <= 1e-9 and out[-1][1] >= 24.0 - 1e-9:
        tail_start = out[-1][0]
        head_end = out[0][1]
        out.pop()
        out[0] = [tail_start, head_end]
    return [(a, b) for a, b in out]


def derive_periods(tou, flat_spread_threshold=FLAT_SPREAD_THRESHOLD):
    """把峰平谷时段推导成 charge / discharge 时段。

    tou 结构::

        {
          "sharp":  [(20, 22)],          # 尖峰（按峰处理，全部放电）
          "peak":   [(14, 22)],
          "flat":   [(6, 11), (13, 14), (22, 24)],
          "valley": [(11, 13), (0, 6)],
          "deep":   [(12, 14)],          # 深谷（比谷更低，也归充电）
          "ratios": {"sharp": 1.85, "peak": 1.72, "flat": 1.0, "valley": 0.38},
        }

    时段用 (start_hour, end_hour) 表示，start > end 表示跨午夜。

    **重叠处理**：放电侧（sharp + peak）与充电侧（valley + deep）各自
    先合并去重再输出。各省政策里尖峰常从峰段里抠出来，两条列表可能重叠，
    合并后只留一份，不影响「这些时刻都是放电」的语义。

    返回 [{"start": 0.0, "end": 8.0, "type": "charge"}, ...]
    """
    valley = _merge_intervals(list(tou.get("valley") or []) +
                              list(tou.get("deep") or []))
    peak = _merge_intervals(list(tou.get("peak") or []) +
                            list(tou.get("sharp") or []))
    flat = _merge_intervals(tou.get("flat") or [])
    ratios = tou.get("ratios") or {}

    periods = []

    if valley:
        # 常规情形：谷充峰放，平段不参与
        for a, b in valley:
            periods.append({"start": a, "end": b, "type": "charge"})
        for a, b in peak:
            periods.append({"start": a, "end": b, "type": "discharge"})
        return periods

    # 无谷段：评估峰平价差，够大才用平段充电
    peak_ratio = float(ratios.get("peak") or ratios.get("sharp") or 0)
    flat_ratio = float(ratios.get("flat") or 1.0)
    if peak_ratio - flat_ratio >= flat_spread_threshold:
        for a, b in flat:
            periods.append({"start": a, "end": b, "type": "charge"})
        for a, b in peak:
            periods.append({"start": a, "end": b, "type": "discharge"})
    return periods


def _months(spec):
    """按「组」构造 12 个月的字典。

    spec: [(月份列表, 峰平谷字典), ...]
    """
    out = {}
    for months, tou in spec:
        for m in months:
            out[str(m)] = tou
    return out


