def list_provinces():
    """已内置的省份名单（按字母序）。"""
    return sorted(PROVINCE_TOU.keys())


def periods_for(province, month):
    """取某省某月的充放电时段（已推导）。找不到返回 []。"""
    p = PROVINCE_TOU.get(province)
    if not p:
        return []
    tou = p["months"].get(str(month))
    if not tou:
        return []
    return derive_periods(tou)
